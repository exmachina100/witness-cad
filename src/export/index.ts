// exportModel(): one entry point for every export format, used by the UI, CLI and MCP server.
import type { RunResult } from '../kernel/runtime';
import { live } from '../kernel/runtime';
import { worldMeshes } from './mesh';
import { to3mf, toGlb, toObj, toPly, toStep, toStlAscii, toStlBinary, toUsda } from './formats';
import { toMjcf, toSdf, toUrdf } from './robot';
import { toDrawingSvg } from './drawing';
import { bomToCsv } from '../kernel/output';
import { zipSync, strToU8 } from 'fflate';

import { EXPORT_FORMATS } from './formats-meta';
export { EXPORT_FORMATS };
export type ExportFormat = keyof typeof EXPORT_FORMATS;

export function exportModel(result: RunResult, format: ExportFormat, opts: { name?: string; transforms?: Record<string, number[]>; assembly?: string } = {}): { data: Uint8Array | string; filename: string; mime: string } {
  const name = (opts.name ?? 'model').replace(/[^\w.-]+/g, '_');
  const meta = EXPORT_FORMATS[format];
  if (!meta) throw new Error(`unknown export format "${format}"`);
  const meshes = () => {
    const m = worldMeshes(result.objects, { transforms: opts.transforms });
    if (!m.length) throw new Error('nothing to export: the model has no solids');
    return m;
  };
  const asm = () => {
    const a = opts.assembly ? live.assemblies.get(opts.assembly) : [...live.assemblies.values()][0];
    if (!a) throw new Error(`${format.toUpperCase()} export needs the script to return an assembly()`);
    return a;
  };
  let data: Uint8Array | string;
  switch (format) {
    case '3mf': data = to3mf(meshes(), name); break;
    case 'stl': data = toStlBinary(meshes()); break;
    case 'stl-ascii': data = toStlAscii(meshes()); break;
    case 'glb': data = toGlb(meshes()); break;
    case 'obj': { const o = toObj(meshes()); data = zipSync({ 'model.obj': strToU8(o.obj), 'model.mtl': strToU8(o.mtl) }); break; }
    case 'ply': data = toPly(meshes()); break;
    case 'step': data = toStep(meshes(), name); break;
    case 'usd': data = toUsda(meshes(), { name, physics: true }); break;
    case 'urdf': data = toUrdf(asm()); break;
    case 'mjcf': data = toMjcf(asm()); break;
    case 'sdf': data = toSdf(asm()); break;
    case 'drawing': data = toDrawingSvg(result, { title: name, transforms: opts.transforms }); break;
    case 'bom': data = bomToCsv(bomRows(result)); break;
    case 'package': {
      const m = meshes();
      const files: Record<string, Uint8Array> = {
        [`${name}.3mf`]: to3mf(m, name), [`${name}.step`]: strToU8(toStep(m, name)),
        [`${name}-drawing.svg`]: strToU8(toDrawingSvg(result, { title: name })), 'bom.csv': strToU8(bomToCsv(bomRows(result))),
        'README.txt': strToU8(`Manufacturing package for ${name}\nGenerated by Witness CAD on ${new Date().toISOString()}\nUnits: millimetres\n\nChecks:\n${result.checks.map((c) => `${c.pass ? 'PASS' : 'FAIL'}  ${c.label}${c.message ? ' — ' + c.message : ''}`).join('\n') || 'none'}\n`),
      };
      for (const mm of m) files[`parts/${mm.name.replace(/[^\w.-]+/g, '_')}.stl`] = toStlBinary([mm]);
      data = zipSync(files);
      break;
    }
    default: throw new Error(`unsupported format ${format}`);
  }
  return { data, filename: `${name}.${meta.ext}`, mime: meta.mime };
}

export function bomRows(result: RunResult) {
  if (result.bom.length) return result.bom;
  // fall back to one row per solid
  const rows = new Map<string, any>();
  for (const o of result.objects) if (o.kind === 'solid' && !o.mock) {
    const key = o.name.replace(/\s*\d+$/, '');
    const r = rows.get(key) ?? { quantity: 0, unit: 'pieces', description: key, dimensions: o.stats ? o.stats.bbox.max.map((v, i) => +(v - o.stats!.bbox.min[i]).toFixed(2)) : undefined };
    r.quantity++;
    rows.set(key, r);
  }
  return [...rows.values()];
}
